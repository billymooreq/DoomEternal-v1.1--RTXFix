template <size_t N>
std::string MaskString(uint64_t mask, const FlagName (&names)[N]) {
  if (mask == 0) return "NONE";
  std::string out;
  for (const FlagName& f : names) {
    if ((mask & f.bit) == 0) continue;
    if (!out.empty()) out += '|';
    out += f.name;
    mask &= ~f.bit;
  }
  if (mask) {
    char hex[32];
    std::snprintf(hex, sizeof(hex), "0x%llx", static_cast<unsigned long long>(mask));
    if (!out.empty()) out += '|';
    out += hex;
  }
  return out;
}

